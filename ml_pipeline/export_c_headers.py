"""Export folded PyTorch weights to C99 headers for ESP32-S3 LumoHub firmware."""

from __future__ import annotations

from pathlib import Path
import numpy as np

from feature_extractor import CLASS_NAMES, FEATURE_NAMES


def _format_1d(name: str, arr: np.ndarray) -> str:
    flat = ", ".join(f"{float(v):.8e}f" for v in arr.ravel())
    return f"static const float {name}[{arr.shape[0]}] = {{\n    {flat}\n}};\n"


def _format_2d(name: str, arr: np.ndarray) -> str:
    rows = []
    for r in range(arr.shape[0]):
        vals = ", ".join(f"{float(v):.8e}f" for v in arr[r])
        rows.append(f"    {{ {vals} }}")
    body = ",\n".join(rows)
    return f"static const float {name}[{arr.shape[0]}][{arr.shape[1]}] = {{\n{body}\n}};\n"


def _format_3d(name: str, arr: np.ndarray) -> str:
    blocks = []
    for d0 in range(arr.shape[0]):
        inner = []
        for d1 in range(arr.shape[1]):
            vals = ", ".join(f"{float(v):.8e}f" for v in arr[d0, d1])
            inner.append(f"        {{ {vals} }}")
        blocks.append("    {\n" + ",\n".join(inner) + "\n    }")
    body = ",\n".join(blocks)
    return (
        f"static const float {name}[{arr.shape[0]}][{arr.shape[1]}][{arr.shape[2]}] = {{\n"
        f"{body}\n}};\n"
    )


def export_cnn_header(
    weights: dict[str, np.ndarray],
    metrics: dict,
    out_paths: list[Path],
) -> None:
    acc = metrics.get("test_accuracy", 0.0)
    f1 = metrics.get("test_macro_f1", 0.0)
    lines = [
        "/**",
        " * @file lumo_hub_cnn_model.h",
        " * @brief Approach 1: Folded 1D-CNN weights for raw [30 x 6] IMU burst classification.",
        f" * Test Accuracy: {acc:.4f} | Macro F1: {f1:.4f}",
        " * Auto-generated by LUMOHUB/ml_pipeline/export_c_headers.py. Do not edit manually.",
        " * Include ONLY inside lumo_imu_ai.c.",
        " */",
        "#pragma once",
        "",
        "#define LUMO_CNN_WINDOW_LEN 30",
        "#define LUMO_CNN_CHANNELS   6",
        "#define LUMO_CNN_CLASSES    5",
        "",
        _format_3d("LUMO_CNN_CONV1_W", weights["conv1_w"]),
        _format_1d("LUMO_CNN_CONV1_B", weights["conv1_b"]),
        _format_3d("LUMO_CNN_CONV2_W", weights["conv2_w"]),
        _format_1d("LUMO_CNN_CONV2_B", weights["conv2_b"]),
        _format_2d("LUMO_CNN_FC1_W", weights["fc1_w"]),
        _format_1d("LUMO_CNN_FC1_B", weights["fc1_b"]),
        _format_2d("LUMO_CNN_FC2_W", weights["fc2_w"]),
        _format_1d("LUMO_CNN_FC2_B", weights["fc2_b"]),
    ]
    content = "\n".join(lines)
    for p in out_paths:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")


def export_mlp_header(
    weights: dict[str, np.ndarray],
    scaler_mean: np.ndarray,
    scaler_std: np.ndarray,
    metrics: dict,
    out_paths: list[Path],
) -> None:
    acc = metrics.get("test_accuracy", 0.0)
    f1 = metrics.get("test_macro_f1", 0.0)
    feat_doc = "\n".join(f" *   [{i:2d}] {name}" for i, name in enumerate(FEATURE_NAMES))
    cls_doc = "\n".join(f" *   [{i}] {name}" for i, name in enumerate(CLASS_NAMES))
    lines = [
        "/**",
        " * @file lumo_hub_feature_model.h",
        " * @brief Approach 2: Folded Physics-Feature MLP weights for 16-feature IMU classification.",
        f" * Test Accuracy: {acc:.4f} | Macro F1: {f1:.4f}",
        " * Features:",
        feat_doc,
        " * Classes:",
        cls_doc,
        " * Auto-generated by LUMOHUB/ml_pipeline/export_c_headers.py. Do not edit manually.",
        " * Include ONLY inside lumo_imu_ai.c.",
        " */",
        "#pragma once",
        "",
        "#define LUMO_MLP_IN_FEATURES 16",
        "#define LUMO_MLP_HIDDEN1     64",
        "#define LUMO_MLP_HIDDEN2     32",
        "#define LUMO_MLP_CLASSES     5",
        "",
        _format_1d("LUMO_MLP_SCALER_MEAN", scaler_mean.astype(np.float32)),
        _format_1d("LUMO_MLP_SCALER_STD", scaler_std.astype(np.float32)),
        _format_2d("LUMO_MLP_FC1_W", weights["fc1_w"]),
        _format_1d("LUMO_MLP_FC1_B", weights["fc1_b"]),
        _format_2d("LUMO_MLP_FC2_W", weights["fc2_w"]),
        _format_1d("LUMO_MLP_FC2_B", weights["fc2_b"]),
        _format_2d("LUMO_MLP_FC3_W", weights["fc3_w"]),
        _format_1d("LUMO_MLP_FC3_B", weights["fc3_b"]),
    ]
    content = "\n".join(lines)
    for p in out_paths:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
